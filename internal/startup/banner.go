// PrintBanner writes the startup banner only when the output is a terminal.
// The banner is always bright magenta. Output failures are ignored
// because this cosmetic output must not prevent application startup.
func PrintBanner(w *os.File) {
	if w == nil {
		return
	}
	printBanner(w, term.IsTerminal(int(w.Fd())))
}

func printBanner(w io.Writer, isTerminal bool) {
	if !isTerminal {
		return
	}
	_, _ = io.WriteString(w, "\x1b[95m"+banner+"\x1b[0m\n")
}
